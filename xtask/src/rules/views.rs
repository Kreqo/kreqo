//! The views of the rules: NOW.md, what needs the founder now; CHECKED.md,
//! what tooling and the AI review check; and LATER.md, what waits for a
//! trigger. Each is built as the prototype built it, as lines joined with
//! newlines, where a rule shown in full is one line that holds several, so
//! that the views stay byte for byte the same.

use super::schema::{Area, Later, Level, Moment, Reminder, Rule, Trigger, Who};
use super::text::{first_sentence, is_space, mentions, words};
use super::{Fact, Rules};

/// The prototype's header, which names it until M3 changes the views' text
/// (docs/decisions.md).
const HEADER: &str =
    "<!-- Generated by compile.py from the TOML rules; edit the TOML, not this file. -->\n\n";

/// The views, and a line that sums up how the rules split.
pub struct Views {
    now: String,
    checked: String,
    later: String,
    pub summary: String,
}

impl Views {
    /// Each view's file name in `views/`, with its text.
    pub fn files(&self) -> [(&'static str, &str); 3] {
        [
            ("NOW.md", &self.now),
            ("CHECKED.md", &self.checked),
            ("LATER.md", &self.later),
        ]
    }
}

/// The views of the rules data.
pub fn render(rules: &Rules) -> Views {
    let split = Split::new(rules);
    Views {
        now: text(&now(rules, &split)),
        checked: text(&checked(rules, &split)),
        later: text(&later(rules, &split)),
        summary: format!(
            "{} rules: {} apply now ({} need you, {} tooling, {} AI review, {} options); {} wait.",
            rules.rules.len(),
            split.active.len(),
            split.yours.len(),
            split.tooling.len(),
            split.reviewed.len(),
            split.options.len(),
            split.waiting.len()
        ),
    }
}

/// The rules as the views split them, each part in the rules' order.
struct Split<'a> {
    /// The rules whose trigger holds.
    active: Vec<&'a Rule>,
    /// The rules whose trigger doesn't hold yet.
    waiting: Vec<&'a Rule>,
    /// The MAY rules that apply.
    options: Vec<&'a Rule>,
    /// The other rules that apply, by who checks them.
    yours: Vec<&'a Rule>,
    tooling: Vec<&'a Rule>,
    reviewed: Vec<&'a Rule>,
}

impl<'a> Split<'a> {
    fn new(rules: &'a Rules) -> Self {
        let (active, waiting): (Vec<&Rule>, Vec<&Rule>) = rules
            .rules
            .iter()
            .partition(|rule| rules.holds(&rule.trigger));
        let checked_by = |who| {
            active
                .iter()
                .copied()
                .filter(|rule| rule.who == who && rule.level != Level::May)
                .collect::<Vec<_>>()
        };
        Self {
            options: active
                .iter()
                .copied()
                .filter(|rule| rule.level == Level::May)
                .collect(),
            yours: checked_by(Who::You),
            tooling: checked_by(Who::Tool),
            reviewed: checked_by(Who::Ai),
            active,
            waiting,
        }
    }
}

/// NOW.md's lines: the principles, the open decisions, the founder's rules
/// by moment, the options and the glossary's terms they use.
fn now(rules: &Rules, split: &Split<'_>) -> Vec<String> {
    let mut body = owned(&[
        "## Principles",
        "",
        "When a case isn't covered, decide by these.",
        "",
    ]);
    body.extend(rules.principles.iter().map(|principle| {
        format!(
            "{}. **{}** {}",
            principle.number, principle.name, principle.text
        )
    }));
    let open: Vec<_> = split
        .active
        .iter()
        .filter_map(|rule| Some((rule, rule.open.as_ref()?)))
        .collect();
    if !open.is_empty() {
        body.extend(owned(&[
            "",
            "## Open decisions",
            "",
            "| Rule | Decision | Leaning |",
            "|---|---|---|",
        ]));
        body.extend(open.iter().map(|(rule, open)| {
            format!(
                "| {} | {} | {} |",
                rule.id,
                open.question,
                or(&open.leaning, "—")
            )
        }));
    }
    let mut moments: Vec<&Moment> = rules.moments.iter().collect();
    moments.sort_by_key(|moment| moment.order);
    let first = moments.first().map(|moment| &moment.id);
    // The words to read now: everything before the first section of rules
    // that isn't the first moment's.
    let mut read_now = None;
    for moment in &moments {
        let group: Vec<&Rule> = split
            .yours
            .iter()
            .copied()
            .filter(|rule| rule.moments.contains(&moment.id))
            .collect();
        if group.is_empty() {
            continue;
        }
        if read_now.is_none() && Some(&moment.id) != first {
            read_now = Some(words(&body));
        }
        body.extend([String::new(), format!("## {}", moment.title), String::new()]);
        body.extend(group.iter().map(|rule| full(rules, rule)));
    }
    let mut now = vec![
        HEADER.to_owned(),
        "# What applies now".to_owned(),
        String::new(),
        format!("Generated for this state: {}.", summary(&rules.state)),
        String::new(),
        format!(
            "Of {} rules, {} apply now. Tooling enforces {} and AI review checks {}; both are listed in CHECKED.md. The {} below need you, and {} are options. The other {} wait for a trigger (LATER.md).",
            rules.rules.len(),
            split.active.len(),
            split.tooling.len(),
            split.reviewed.len(),
            split.yours.len(),
            split.options.len(),
            split.waiting.len()
        ),
        String::new(),
        format!(
            "Read the principles, the open decisions and the first section now, about {} words. Read each later section when its moment comes.",
            read_now.unwrap_or_else(|| words(&body))
        ),
        String::new(),
    ];
    now.extend(body);
    if !split.options.is_empty() {
        now.extend(owned(&[
            "",
            "## Options",
            "",
            "These MAY rules are yours to take or leave.",
            "",
        ]));
        now.extend(split.options.iter().map(|rule| full(rules, rule)));
    }
    let lowercased = now.join("\n").to_lowercase();
    let used: Vec<_> = rules
        .glossary
        .iter()
        .filter(|term| mentions(&lowercased, &term.term))
        .collect();
    if !used.is_empty() {
        now.extend(owned(&["", "## Terms used here", ""]));
        now.extend(
            used.iter()
                .map(|term| format!("- **{}:** {}", term.term, term.definition)),
        );
    }
    now
}

/// CHECKED.md's lines: the rules that tooling enforces and those the AI
/// review checks, by area.
fn checked(rules: &Rules, split: &Split<'_>) -> Vec<String> {
    let mut checked = vec![
        HEADER.to_owned(),
        "# Checked for you".to_owned(),
        String::new(),
        format!(
            "These {} rules apply now, and tooling or an AI review checks them, so you don't need to read them in advance. A failed check names its rule; look it up here.",
            split.tooling.len() + split.reviewed.len()
        ),
        String::new(),
    ];
    for (title, group) in [
        ("Enforced by tooling", &split.tooling),
        ("Checked by AI review", &split.reviewed),
    ] {
        checked.extend([format!("## {title} ({})", group.len()), String::new()]);
        for (area, in_area) in by_area(&rules.areas, group) {
            checked.extend([
                format!("### {} ({})", area.title, area.prefix),
                String::new(),
            ]);
            for rule in in_area {
                let current = rules.current(rule);
                checked.extend([
                    format!("**{}** · {} · {}\\", rule.id, rule.level, current.statement),
                    format!("*Verified by:* {}", current.verification),
                    String::new(),
                ]);
            }
        }
    }
    checked
}

/// LATER.md's lines: a table of the triggers that don't hold yet, then for
/// each one the rules it starts, the rules it changes and its reminders.
fn later(rules: &Rules, split: &Split<'_>) -> Vec<String> {
    let mut later = vec![
        HEADER.to_owned(),
        "# What waits".to_owned(),
        String::new(),
        // Like the header, it names the prototype until M3.
        format!(
            "These {} rules don't apply yet. Each waits for a trigger: set the matching fact in state.toml, rerun compile.py, and its rules move into NOW.md or CHECKED.md. Rules that apply now but change at a trigger, and reminders, are listed under that trigger too.",
            split.waiting.len()
        ),
        String::new(),
        "| Trigger | Condition | Rules | Need you | Changes |".to_owned(),
        "|---|---|---|---|---|".to_owned(),
    ];
    let mut sections = Vec::new();
    let mut triggers: Vec<&Trigger> = rules.triggers.iter().collect();
    triggers.sort_by_key(|trigger| trigger.order);
    for trigger in triggers {
        if rules.holds(&trigger.id) {
            continue;
        }
        let starting: Vec<&Rule> = split
            .waiting
            .iter()
            .copied()
            .filter(|rule| rule.trigger == trigger.id)
            .collect();
        let changes: Vec<(&Rule, &Later)> = rules
            .rules
            .iter()
            .flat_map(|rule| {
                rule.later
                    .iter()
                    .filter(|version| version.trigger == trigger.id)
                    .map(move |version| (rule, version))
            })
            .collect();
        let notes: Vec<(&Rule, &Reminder)> = rules
            .rules
            .iter()
            .flat_map(|rule| {
                rule.reminder
                    .iter()
                    .filter(|note| note.trigger == trigger.id)
                    .map(move |note| (rule, note))
            })
            .collect();
        if starting.is_empty() && changes.is_empty() && notes.is_empty() {
            continue;
        }
        let (need, rest): (Vec<&Rule>, Vec<&Rule>) = starting
            .iter()
            .copied()
            .partition(|rule| rule.who == Who::You);
        later.push(format!(
            "| {} | `{}` | {} | {} | {} |",
            trigger.title,
            trigger.when,
            starting.len(),
            need.len(),
            changes.len()
        ));
        sections.extend([
            String::new(),
            format!("## {}", trigger.title),
            String::new(),
            format!("*Condition:* `{}`", trigger.when),
            String::new(),
        ]);
        if !need.is_empty() {
            sections.extend([format!("### Needs you ({})", need.len()), String::new()]);
            sections.extend(need.iter().map(|rule| full(rules, rule)));
        }
        if !rest.is_empty() {
            sections.extend([
                format!("### Checked for you ({})", rest.len()),
                String::new(),
            ]);
            sections.extend(rest.iter().map(|rule| {
                let by = if rule.who == Who::Tool {
                    "tooling"
                } else {
                    "AI review"
                };
                format!(
                    "- **{}** · {} · {} *({by})*",
                    rule.id,
                    rule.level,
                    first_sentence(&rule.statement)
                )
            }));
            sections.push(String::new());
        }
        if !changes.is_empty() {
            sections.extend(owned(&["### Rules that change", ""]));
            for (rule, version) in changes {
                sections.extend([
                    format!("**{}** becomes: {}", rule.id, version.statement),
                    String::new(),
                ]);
            }
        }
        if !notes.is_empty() {
            sections.extend(owned(&["### Reminders", ""]));
            sections.extend(
                notes
                    .iter()
                    .map(|(rule, note)| format!("- **{}:** {}", rule.id, note.note)),
            );
            sections.push(String::new());
        }
    }
    later.extend(sections);
    later
}

/// A rule in full, as NOW.md and LATER.md show the rules that need the
/// founder: its statement, why, where it's checked and any open decision.
fn full(rules: &Rules, rule: &Rule) -> String {
    let current = rules.current(rule);
    let mut text = format!(
        "**{}** · {} · {}\\\n*Why:* {} · *{}.*",
        rule.id,
        rule.level,
        current.statement,
        current.rationale,
        current.check.described()
    );
    if let Some(open) = &rule.open {
        text += &format!(
            "\\\n*Open decision:* {}. Leaning: {}.",
            open.question,
            or(&open.leaning, "none yet")
        );
    }
    text.push('\n');
    text
}

/// The rules of each area, in the areas' order, leaving out the areas that
/// have none.
fn by_area<'a>(areas: &'a [Area], rules: &[&'a Rule]) -> Vec<(&'a Area, Vec<&'a Rule>)> {
    areas
        .iter()
        .filter_map(|area| {
            let in_area: Vec<&Rule> = rules
                .iter()
                .copied()
                .filter(|rule| rule.prefix() == area.prefix)
                .collect();
            (!in_area.is_empty()).then_some((area, in_area))
        })
        .collect()
}

/// The state as NOW.md gives it: each fact that holds or counts, in the
/// file's order, and then whether every other fact is false.
fn summary(state: &[(String, Fact)]) -> String {
    let is_false = |fact: &Fact| *fact == Fact::Holds(false);
    let mut summary = state
        .iter()
        .filter(|(_, fact)| !is_false(fact))
        .map(|(name, fact)| format!("{name} = {fact}"))
        .collect::<Vec<_>>()
        .join("; ");
    if state.iter().any(|(_, fact)| is_false(fact)) {
        summary += "; every other fact is false";
    }
    summary
}

/// A view's text: its lines joined, ending in one newline.
fn text(lines: &[String]) -> String {
    let mut text = lines.join("\n").trim_end_matches(is_space).to_owned();
    text.push('\n');
    text
}

/// The text, or the fallback when the text is empty.
fn or<'a>(text: &'a str, fallback: &'a str) -> &'a str {
    if text.is_empty() { fallback } else { text }
}

/// The lines, as owned strings.
fn owned(lines: &[&str]) -> Vec<String> {
    lines.iter().map(|&line| line.to_owned()).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    // The expected answers are the prototype's.

    #[test]
    fn sums_up_the_state_as_the_prototype_did() {
        let fact = |name: &str, fact| (name.to_owned(), fact);
        assert_eq!(
            summary(&[
                fact("maintainers", Fact::Count(1)),
                fact("open", Fact::Holds(false))
            ]),
            "maintainers = 1; every other fact is false"
        );
        assert_eq!(
            summary(&[
                fact("zeta", Fact::Holds(true)),
                fact("alpha", Fact::Count(0)),
                fact("mid", Fact::Holds(false)),
            ]),
            "zeta = true; alpha = 0; every other fact is false"
        );
        assert_eq!(summary(&[fact("open", Fact::Holds(true))]), "open = true");
        assert_eq!(
            summary(&[fact("open", Fact::Holds(false))]),
            "; every other fact is false"
        );
    }

    #[test]
    fn ends_a_view_with_one_newline() {
        let lines = owned(&["a", "  b \u{2003}\u{1c}", "", ""]);
        assert_eq!(text(&lines), "a\n  b\n");
    }
}
